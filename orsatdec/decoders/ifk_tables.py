def _mfsk_dec():
    return {int(s, 2): c for c, s in enumerate(MFSK_VARICODE)}


def _domino_dec():
    d = {}
    for c, k in enumerate(DOMINO_VARICODE):
        nib = [k[0]]
        for x in k[1:]:
            if x & 8:
                nib.append(x)
            else:
                break
        sym = 0
        for i, x in enumerate(reversed(nib)):
            sym |= x << (4 * i)
        d[sym] = c if c < 256 else (c - 256) | 0x100      # comme fldigi : le dernier l'emporte
    return d


def _thor_dec():
    d = _mfsk_dec()
    for i, s in enumerate(THOR_SEC_VARICODE):
        d.setdefault(int(s, 2), (32 + i) | 0x100)
    return d


MFSK_VARIDEC = _mfsk_dec()        # code (int, sans les zéros de séparation) -> octet
DOMINO_VARIDEC = _domino_dec()    # quartets concaténés (premier en poids fort) -> octet | 0x100 si secondaire
THOR_VARIDEC = _thor_dec()        # idem MFSK, plus 0x100 | car. pour le jeu secondaire
