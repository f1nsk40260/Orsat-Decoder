ROWS = 28          # échantillons par colonne (2 par point émis)


class Hell(Decoder):
    name = "Hell"
    kind = "img"

    def __init__(self, fs, af=1000.0, mode="feld", reverse=False, squelch=True, hrep=3, blackboard=False):
        super().__init__(fs, af)
        self.mode = mode
        self.label, self.colrate, self.kind_mod, self.shift = HELL_MODES[mode]
        self.pixrate = 14 * self.colrate
        self.reverse = reverse
        self.squelch = squelch
        self.hrep = max(1, int(hrep))
        self.blackboard = blackboard
        self.af0 = float(af)
        if self.kind_mod == "am":
            cut = 0.45 * self.pixrate
            self.sig_bw = self.pixrate                     # occupation (±pixrate/2)
        else:
            cut = self.shift / 2 + 0.6 * self.pixrate
            self.sig_bw = self.shift + self.pixrate
        self.mix = Mixer(af, self.fs)
        if cut < 150:
            # modes lents : décimation en deux étages (un seul filtre serait très long)
            D1 = max(1, int(self.fs // 1000))
            self.pre_fir = FirDecim(lowpass(self.fs, 250, 4 * self.fs / 250), D1)
            fs1 = self.fs / D1
        else:
            self.pre_fir, D1, fs1 = None, 1, self.fs
        D2 = max(1, int(fs1 // (8 * self.pixrate)))
        self.fir = FirDecim(lowpass(fs1, cut, 4 * fs1 / cut), D2)
        self.fs2 = fs1 / D2
        self.prev = 0j
        self.spr = self.fs2 / (self.colrate * ROWS)        # échantillons (fs2) par point reçu
        self.buf = np.zeros(0)                             # enveloppe ou fréquence instantanée
        self.pos = 0.0                                     # position (dans buf) du prochain point
        self.hist = np.zeros(0)                            # derniers points (CAG)
        self.peak = 1e-9
        self.stream = np.zeros(0, np.uint8)                # points gris pas encore mis en colonnes
        self.prev_col = np.full(ROWS, 255, np.uint8)
        self.started = False
        self.pre = []                                      # colonnes retenues silencieux fermé
        self.out_cols = []
        self.raw = np.zeros(0)
        self.since_sq = 0
        self.open = not squelch
        self.hold = 0.0
        self.snr = 0.0
        self.since_out = 0
        self.span = 40.0
        self.finder = ToneFinder(self.fs, seconds=1.0, period=1.0)

    def set_af(self, af):
        super().set_af(af)
        self.af0 = float(af)
        self.mix.freq = float(af)
        self.span = 20.0

    def status(self):
        return {"af": round(float(self.mix.freq), 1), "snr": round(float(self.snr), 1),
                "sync": 1 if self.open else 0, "mode": self.label}

    # ---------------------------------------------------------------- silencieux / CAF
    def _squelch(self):
        n = len(self.raw)
        if n < int(0.5 * self.fs):
            return
        if getattr(self, "_win", None) is None or len(self._win) != n:
            self._win = np.hanning(n)
        sp = np.abs(np.fft.rfft(self.raw * self._win)) ** 2
        fq = np.fft.rfftfreq(n, 1 / self.fs)
        c = self.mix.freq
        h = self.sig_bw / 2
        ib = np.abs(fq - c) < max(h, 30)
        ob = (np.abs(fq - c) > h + 150) & (np.abs(fq - c) < h + 450) & (fq > 100) & (fq < self.fs / 2 - 100)
        if not ib.any() or not ob.any():
            return
        ratio = np.mean(sp[ib]) / (np.mean(sp[ob]) + 1e-20)
        self.snr = float(10 * np.log10(max(ratio - 1, 1e-3) * 2 * max(h, 30) / 2500))
        self.ratio_s = 0.5 * (getattr(self, "ratio_s", 1.0) + ratio)    # moyenne sur ~0,5 s
        if self.ratio_s > 1.2:
            self.hold = 2.0
        if self.squelch:
            self.open = self.hold > 0

    def _afc(self, x):
        if self.finder.feed(x):
            if self.kind_mod == "fsk":
                fc = self.finder.find(self.af0, self.span, shift=self.shift, min_ratio=6.0)
            else:
                fc = self.finder.find(self.af0, self.span, min_ratio=10.0)
            if fc is not None and abs(fc - self.mix.freq) > 3:
                self.mix.freq = fc

    # ---------------------------------------------------------------- traitement
    def process(self, x):
        x = np.asarray(x, np.float64)
        self._afc(x)
        self.raw = np.concatenate([self.raw, x])[-int(self.fs):]
        self.since_sq += len(x)
        if self.since_sq >= self.fs / 4:
            self.hold -= self.since_sq / self.fs
            self.since_sq = 0
            self._squelch()
        z = self.mix.process(x)
        if self.pre_fir is not None:
            z = self.pre_fir.process(z)
        z = self.fir.process(z)
        if len(z) == 0:
            return []
        if self.kind_mod == "am":
            y = np.abs(z)
        else:
            zz = np.concatenate([[self.prev], z])
            y = np.angle(zz[1:] * np.conj(zz[:-1])) * self.fs2 / (2 * np.pi)
        self.prev = z[-1]
        self.buf = np.concatenate([self.buf, y])
        # points reçus (moyenne sur la durée de chaque point)
        n = int((len(self.buf) - self.pos - 1) // self.spr)
        if n <= 0:
            return []
        v = box_sample(self.buf, self.pos - 0.5, self.spr, n)
        self.pos += n * self.spr
        cut = int(self.pos) - 2
        if cut > 0:
            self.buf = self.buf[cut:]
            self.pos -= cut
        g = self._gray(v)
        self.stream = np.concatenate([self.stream, g])
        nc = len(self.stream) // ROWS
        cols = []
        for i in range(nc):
            c = self.stream[i * ROWS:(i + 1) * ROWS][::-1]           # bas → haut à l'émission
            cols.append(np.concatenate([c, self.prev_col]))
            self.prev_col = c
        self.stream = self.stream[nc * ROWS:]
        ev = []
        if self.open:
            if not self.started:
                self.started = True
                ev.append({"t": "img", "op": "new", "w": 0, "h": 2 * ROWS, "fmt": "gray", "tape": True,
                           "title": self.label})
            self.out_cols.extend(self.pre)
            self.pre = []
            self.out_cols.extend(cols)
        else:
            # mémoire de ~1 s : le début de l'émission n'est pas perdu à l'ouverture
            self.pre = (self.pre + cols)[-int(np.ceil(self.colrate)) - 1:]
        self.since_out += len(x)
        if self.out_cols and (self.since_out >= self.fs / 2 or not self.open):
            self.since_out = 0
            arr = np.repeat(np.array(self.out_cols, np.uint8), self.hrep, axis=0)
            self.out_cols = []
            ev.append({"t": "img", "op": "cols", "n": len(arr), "data": b64(arr)})
        return ev

    def _gray(self, v):
        """Intensité → gris (0 = noir = signal présent, comme l'encre sur le papier)."""
        if self.kind_mod == "fsk":
            s = 0.5 - v / self.shift                   # tonalité basse = point noir
            if self.reverse:
                s = 1 - s
            ink = np.clip(s, 0, 1)
        else:
            # CAG : crête suivie (montée immédiate, descente ~3 s), fond = 20e centile récent
            self.hist = np.concatenate([self.hist, v])[-int(3 * self.colrate * ROWS):]
            self._agc_n = getattr(self, "_agc_n", 1 << 30) + len(v)
            if self._agc_n >= self.colrate * ROWS / 4:          # centiles recalculés 4 fois par seconde
                self._agc_n = 0
                self._pk, self._fl = np.percentile(self.hist, [99, 20])
            pk, fl = self._pk, self._fl
            dec = np.exp(-len(v) / (3 * self.colrate * ROWS))
            self.peak = max(pk, self.peak * dec, 1e-12)
            ink = np.clip((v - fl) / max(self.peak - fl, 1e-12), 0, 1)
        g = ink if self.blackboard else 1 - ink
        return np.round(g * 255).astype(np.uint8)
