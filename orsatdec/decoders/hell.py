"""Hellschreiber : Feld Hell (AM, 122,5 bauds, 17,5 colonnes/s de 14 points), Slow Hell, Hell X5 / X9,
FSK Hell 245 / 105 et Hell 80 (FSK), d'après fldigi (src/feld).

Le Hell n'a ni synchro ni code : le récepteur « imprime » simplement l'intensité du signal, colonne par
colonne, et c'est l'œil qui lit. Chaque colonne est échantillonnée à 2 points par point émis
(28 échantillons), du bas vers le haut comme à l'émission.
Rendu en « bande » (tape) : comme sur les vrais téléimprimeurs Hell (hélice à deux spires) chaque
colonne est imprimée deux fois, l'une au-dessus de l'autre (colonne courante en haut, colonne précédente
en bas) : une erreur de vitesse fait monter ou descendre l'écriture mais une ligne de texte complète
reste toujours lisible. Chaque colonne est répétée hrep fois en largeur pour que les points soient à
peu près carrés (point de 4 rangées × 3 colonnes par défaut).
Niveaux de gris avec CAG (crête et fond suivis sur ~3 s) ; silencieux par comparaison de la densité
spectrale dans la bande du signal et à côté, avec mémoire pour ne pas perdre le début.
"""
